def pipe4(line):
    """char span 1..pos of the 4th '|' in a symbol-assignment table row"""
    n = 0
    for i, ch in enumerate(line):
        if ch == "|":
            n += 1
            if n == 4:
                return i + 1  # 1-based inclusive
    raise ValueError("no 4th pipe: " + line[:60])

