# ---- build ---------------------------------------------------------------
DECLARED = {F1: F1, F2: F2, F3: F3, F4: F4, F5: F5, F6: F6, F7: F7, F8: F8}
ORDER = [F1, F2, F3, F4, F5, F6, F7, F8]

report = []
for path in ORDER:
    src = lines_of(path)
    n = len(src)
    ranges = list(SPECS[path])
    if path == F5:
        for ln in SYMROWS:
            ranges.append([ln, ln, "A", "G1", 1, pipe4(src[ln-1])])
    ranges.sort(key=lambda r: (r[0], r[1]))
    # validate tiling
    cur = 1
    for r in ranges:
        if r[0] != cur:
            sys.exit("TILING ERROR %s at %s (expected %d)" % (path, r, cur))
        if r[1] < r[0]:
            sys.exit("BAD RANGE %s %s" % (path, r))
        cur = r[1] + 1
    if cur - 1 != n:
        sys.exit("COVERAGE ERROR %s: ends at %d, n=%d" % (path, cur-1, n))
    counts = {"A": 0, "W": 0, "I": 0, "B": 0}
    for r in ranges:
        counts[r[2]] += (r[1] - r[0] + 1)
    assert sum(counts.values()) == n, (path, counts, n)
    obj = {"file": DECLARED[path], "n": n, "ranges": ranges}
    fname = DECLARED[path].replace("/", "__") + ".json"
    outp = os.path.join(OUT, fname)
    with open(outp, "w", encoding="utf-8") as fh:
        json.dump(obj, fh, ensure_ascii=False)
        fh.write("\n")
    report.append("WROTE %s | n=%d | ranges=%d | A=%d W=%d I=%d B=%d | COVERAGE 1-%d no gaps no overlaps"
                  % (outp, n, len(ranges), counts["A"], counts["W"], counts["I"], counts["B"], n))

print("\n".join(report))
